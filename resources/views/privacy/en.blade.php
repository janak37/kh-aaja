<h1>Privacy</h1>
<p class="text-zinc-500">Kh-aaja is built to know as little about you as possible. Last updated 14 November 2026.</p>

<h2>When you browse</h2>
<ul>
    <li>You don't need an account.</li>
    <li>Your favourites (♥) are saved only on your phone. We can't see what you saved.</li>
    <li>When you tap ♥, we only add 1 to that shop's or dish's count. We never store your IP address, only a scrambled code that stops one person from tapping ♥ many times.</li>
    <li>We use two small cookies: one remembers your language, and one keeps the site secure. No advertising or tracking cookies.</li>
</ul>

<h2>When you reserve a dish</h2>
<ul>
    <li>We ask for your name and phone number, and an optional note.</li>
    <li>Only that shop sees them, so they can contact you about your order.</li>
    <li>The shop stops seeing your phone number 2 days after the reservation date, and your status link stops working.</li>
    <li>After {{ $days }} days we erase your name, phone number and note completely. We keep only something like "2 × Jhol Momo, confirmed", with nothing about you, to calculate the shop's score.</li>
</ul>

<h2>What we never do</h2>
<ul>
    <li>Sell or share your information.</li>
    <li>Show ads.</li>
    <li>Send you marketing messages.</li>
</ul>

<h2>Shop owners</h2>
<ul>
    <li>Your shop name, area, address, phone, WhatsApp, menu and hours are public. That's what your board is for.</li>
    <li>Your login email and password are private. Passwords are stored scrambled (hashed), so even we can't read them.</li>
</ul>

